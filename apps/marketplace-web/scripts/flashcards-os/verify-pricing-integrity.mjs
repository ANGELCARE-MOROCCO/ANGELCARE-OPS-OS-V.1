import fs from 'node:fs';import path from 'node:path'
const root=process.argv[2]?path.resolve(process.argv[2]):process.cwd();const f=path.join(root,'lib/flashcards-os/solutions/server/pricing.ts');const s=fs.readFileSync(f,'utf8')
const checks=[];const add=(n,o)=>checks.push([n,Boolean(o)])
add('pricing kernel exists',fs.existsSync(f))
add('prices are sourced from release facts',s.includes('basePriceDh'))
add('costs are sourced from release facts',s.includes('unitCostDh'))
add('missing price is blocking or warned',/missing.*price|price.*missing/i.test(s))
add('missing cost is visible',/missing.*cost|cost.*missing/i.test(s))
add('discount is clamped',s.includes('maximumDiscountPercent')&&s.includes('Math.min'))
add('tax is explicit and deterministic',s.includes('taxPercent')&&s.includes('taxDh'))
add('gross margin amount is calculated',s.includes('grossMarginDh'))
add('gross margin percentage is calculated',s.includes('grossMarginPercent'))
add('minimum margin eligibility is checked',s.includes('minimumMarginPercent')&&s.includes('marginEligible'))
add('negative margin publication is blocked',/Negative(?: gross)? margin|negative(?: gross)? margin/i.test(s))
add('currency is Dh',s.includes("currency:'Dh'")||s.includes("currency: 'Dh'"))
add('pricing kernel contains no AI/provider call',!s.includes('fetch(')&&!s.includes('openrouter')&&!s.includes('tavily'))
for(const [n,o] of checks)console.log(`${o?'PASS':'FAIL'}  ${n}`)
const fail=checks.filter(([,o])=>!o);console.log(`\n${checks.length-fail.length}/${checks.length} pricing-integrity checks passed.`);if(fail.length)process.exit(1)
