import fs from 'node:fs';import path from 'node:path'
const root=process.argv[2]?path.resolve(process.argv[2]):process.cwd();const f=path.join(root,'lib/flashcards-os/solutions/server/journey-engine.ts');const s=fs.readFileSync(f,'utf8')
const checks=[];const add=(n,o)=>checks.push([n,Boolean(o)])
add('journey engine exists',fs.existsSync(f))
add('duration is validated',s.includes('durationDays'))
add('sessions per day are validated',s.includes('sessionsPerDay'))
add('minutes per session are validated',s.includes('minutesPerSession'))
add('maximum collections are enforced',s.includes('maximumCollections')&&s.includes('slice(0,input.request.maximumCollections)'))
add('required releases are preserved',s.includes('requiredReleaseIds'))
add('excluded releases are removed',s.includes('excludedReleaseIds'))
add('unapproved arbitrary IDs are filtered by candidate map',s.includes('candidateMap.has'))
add('days are capped to request duration',s.includes('slice(0,input.request.durationDays)'))
add('sessions are capped to sessions per day',s.includes('slice(0,input.request.sessionsPerDay)'))
add('session duration is reset to governed duration',s.includes('durationMinutes:input.request.minutesPerSession'))
add('workload findings are generated',s.includes('workloadFindings'))
add('baseline assessment is required',s.includes('baseline'))
add('midpoint review is required',s.includes('midpointReview'))
add('final assessment is required',s.includes('finalAssessment'))
add('mastery criteria are required',s.includes('masteryCriteria'))
add('adaptations are retained',s.includes('adaptations'))
add('plans are limited through clampScenarioCount',s.includes('clampScenarioCount'))
for(const [n,o] of checks)console.log(`${o?'PASS':'FAIL'}  ${n}`)
const fail=checks.filter(([,o])=>!o);console.log(`\n${checks.length-fail.length}/${checks.length} journey-workload checks passed.`);if(fail.length)process.exit(1)
