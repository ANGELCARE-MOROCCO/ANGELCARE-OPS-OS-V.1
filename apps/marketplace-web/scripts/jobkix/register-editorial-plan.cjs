const fs=require('node:fs'),path=require('node:path'),os=require('node:os'),cp=require('node:child_process');
const app=path.resolve(__dirname,'../..');
const [planFile,receiptFile]=process.argv.slice(2);
if(!planFile||!receiptFile)throw Error('Usage: register-editorial-plan plan.json receipt.json');
const plan=JSON.parse(fs.readFileSync(planFile,'utf8')),receipts=JSON.parse(fs.readFileSync(receiptFile,'utf8'));
const temp=fs.mkdtempSync(path.join(os.tmpdir(),'jobkix-editorial-prompts-'));
for(const item of plan){
 const receipt=receipts.find(r=>r.id===item.id);
 if(!receipt?.source)throw Error('Missing generated bytes: '+item.id);
 const promptFile=path.join(temp,item.id+'.txt');fs.writeFileSync(promptFile,item.prompt);
 const result=cp.spawnSync(process.execPath,[path.join(__dirname,'register-editorial.cjs'),item.id,receipt.source,item.subject,promptFile],{cwd:app,encoding:'utf8'});
 if(result.status!==0)throw Error(result.stderr||result.stdout);
 process.stdout.write(result.stdout);
}
