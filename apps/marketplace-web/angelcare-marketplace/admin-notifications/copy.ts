export function familyLabel(f: string, l: Locale) {
  const a = familyNames[f];
  return a ? a[l === "fr" ? 0 : l === "en" ? 1 : 2] : f;
}
export function timeLabel(at: string, l: Locale, full = false) {
  const d = new Date(at);
  return Number.isFinite(d.getTime())
    ? new Intl.DateTimeFormat(
        l === "ar" ? "ar-MA" : l === "fr" ? "fr-MA" : "en-GB",
        {
          timeZone: "Africa/Casablanca",
          day: "2-digit",
          month: "short",
          ...(full ? { year: "numeric" as const } : {}),
          hour: "2-digit",
          minute: "2-digit",
          ...(full ? { timeZoneName: "short" as const } : {}),
        },
      ).format(d)
    : "—";
}
export function timeGroup(at: string, l: Locale) {
  const day = (v: Date) =>
      new Intl.DateTimeFormat("en-CA", {
        timeZone: "Africa/Casablanca",
        year: "numeric",
        month: "2-digit",
        day: "2-digit",
      }).format(v),
    now = new Date();
  return day(new Date(at)) === day(now)
    ? copy(l).today
    : day(new Date(at)) === day(new Date(now.getTime() - 86400000))
      ? copy(l).yesterday
      : copy(l).older;
}
