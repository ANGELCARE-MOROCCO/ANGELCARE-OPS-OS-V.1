const csv=(value:unknown)=>`"${String(value??'').replaceAll('"','""')}"`
export function studioDeveloperContractCsv(){
  const rows=[['category','category_title','alias','label','canonical_type','variant']]
  for(const category of ANGELCARE_STUDIO_DEVELOPER_CONTRACT.visualCatalogue)for(const row of category.experiences)rows.push([category.key,category.title,row.key,row.label,row.canonicalType,row.variant])
  return rows.map(row=>row.map(csv).join(',')).join('\n')+'\n'
}
